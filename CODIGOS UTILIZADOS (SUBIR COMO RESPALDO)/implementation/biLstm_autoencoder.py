"""
Bi-LSTM autoencoder for behavioral anomaly detection (IPNV).

Consumes the tensors generated by pipeline_ipnv_corregido.py (stage 3) and
runs the four phases of the unsupervised anomaly-detection system:

    PHASE 1  Train the autoencoder on healthy swimming ONLY (X_train),
             watching X_val for early stopping.
    PHASE 2  Calibrate the threshold tau = P99.5 of the error on X_calibracion.
    PHASE 3  Specificity test: rho on unseen healthy fish (holdout).
             rho should be low (~0.5%). Measures false positives.
    PHASE 4  Sensitivity test: rho per infected video. rho is expected to
             grow with days post-infection.

The model is trained a single time (phase 1) and the threshold is fixed a
single time (phase 2). Phases 3 and 4 only apply that already-fixed model
and threshold, they never adjust them based on what they see in
control_holdout or test.
"""

