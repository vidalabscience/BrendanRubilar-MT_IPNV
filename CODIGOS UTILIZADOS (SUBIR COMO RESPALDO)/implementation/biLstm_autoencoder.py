DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")



# MODEL — Bi-LSTM autoencoder (encoder-decoder scheme)

class BiLSTMAutoencoder(nn.Module):
    """A Bi-LSTM encoder compresses the window into a latent vector. An LSTM
    decoder reconstructs the full sequence from that vector, repeated T times.

    Input  : (batch, T, F)
    Output : (batch, T, F)  -> reconstruction of the input
    """
    def __init__(self, n_features, hidden, latent, num_layers=1, dropout=0.0):
        super().__init__()
        self.T = None  # set in forward() based on the input

        # --- ENCODER: Bi-LSTM. Being bidirectional, its output is 2*hidden. ---
        self.encoder = nn.LSTM(
            input_size=n_features, hidden_size=hidden, num_layers=num_layers,
            batch_first=True, bidirectional=True,
            dropout=dropout if num_layers > 1 else 0.0)
        # Projects the final state (2*hidden from bidirectionality) into the latent.
        self.to_latent = nn.Linear(2 * hidden * num_layers, latent)

        # --- DECODER: unidirectional LSTM that reconstructs the sequence. -----
        self.from_latent = nn.Linear(latent, hidden)
        self.decoder = nn.LSTM(
            input_size=hidden, hidden_size=hidden, num_layers=num_layers,
            batch_first=True,
            dropout=dropout if num_layers > 1 else 0.0)
        self.output_layer = nn.Linear(hidden, n_features)

    def forward(self, x):
        B, T, F = x.shape
        # ENCODE: take the last hidden state from both directions.
        _, (h_n, _) = self.encoder(x)          # h_n: (2*num_layers, B, hidden)
        h_cat = h_n.permute(1, 0, 2).reshape(B, -1)  # (B, 2*hidden*num_layers)
        z = self.to_latent(h_cat)              # (B, latent) -> bottleneck

        # DECODE: repeat the latent T steps and reconstruct the sequence.
        dec_in = self.from_latent(z).unsqueeze(1).repeat(1, T, 1)  # (B, T, hidden)
        dec_out, _ = self.decoder(dec_in)      # (B, T, hidden)
        return self.output_layer(dec_out)      # (B, T, F)



# UTILITIES

def cargar(nombre):
    ruta = os.path.join(CFG["DIR_TENSORES"], nombre)
    return np.load(ruta)


def error_por_ventana(modelo, X, batch=2048):
    """Reconstruction MSE for EACH window (a vector of length N): this is
    the per-window anomaly score every phase below is built on."""
    modelo.eval()
    errores = []
    with torch.no_grad():
        for i in range(0, len(X), batch):
            xb = torch.from_numpy(X[i:i+batch]).float().to(DEVICE)
            rec = modelo(xb)
            # MSE averaged over T and F -> a single scalar per window.
            e = ((rec - xb) ** 2).mean(dim=(1, 2))
            errores.append(e.cpu().numpy())
    return np.concatenate(errores)



# PHASE 1 — TRAINING

def fase1_entrenar():
    print("\n=== PHASE 1: TRAINING THE AUTOENCODER (healthy swimming only) ===")
    torch.manual_seed(CFG["SEED"]); np.random.seed(CFG["SEED"])
    os.makedirs(CFG["DIR_SALIDA"], exist_ok=True)

    X_train = cargar("X_train.npy")
    X_val   = cargar("X_val.npy")
    print(f"   X_train: {X_train.shape}   X_val: {X_val.shape}")

    tr_loader = DataLoader(
        TensorDataset(torch.from_numpy(X_train).float()),
        batch_size=CFG["BATCH"], shuffle=True, num_workers=4, pin_memory=True)
    va_loader = DataLoader(
        TensorDataset(torch.from_numpy(X_val).float()),
        batch_size=CFG["BATCH"], shuffle=False, num_workers=4, pin_memory=True)

    modelo = BiLSTMAutoencoder(
        CFG["N_FEATURES"], CFG["HIDDEN"], CFG["LATENT"],
        CFG["NUM_LAYERS"], CFG["DROPOUT"]).to(DEVICE)
    opt = torch.optim.Adam(modelo.parameters(), lr=CFG["LR"])
    loss_fn = nn.MSELoss()

    mejor_val, sin_mejora, historia = float("inf"), 0, []
    ruta_modelo = os.path.join(CFG["DIR_SALIDA"], "bilstm_ae.pt")

    for ep in range(1, CFG["EPOCHS"] + 1):
        # --- train ---
        modelo.train(); tr_loss = 0.0
        for (xb,) in tr_loader:
            xb = xb.to(DEVICE, non_blocking=True)
            opt.zero_grad()
            loss = loss_fn(modelo(xb), xb)
            loss.backward()
            opt.step()
            tr_loss += loss.item() * len(xb)
        tr_loss /= len(X_train)

        # --- val ---
        modelo.eval(); va_loss = 0.0
        with torch.no_grad():
            for (xb,) in va_loader:
                xb = xb.to(DEVICE, non_blocking=True)
                va_loss += loss_fn(modelo(xb), xb).item() * len(xb)
        va_loss /= len(X_val)
        historia.append({"epoch": ep, "train_loss": tr_loss, "val_loss": va_loss})
        print(f"   Epoch {ep:3d} | train={tr_loss:.6f} | val={va_loss:.6f}")

        # --- early stopping ---
        if va_loss < mejor_val - 1e-6:
            mejor_val, sin_mejora = va_loss, 0
            torch.save(modelo.state_dict(), ruta_modelo)  # saves the best checkpoint
        else:
            sin_mejora += 1
            if sin_mejora >= CFG["PATIENCE"]:
                print(f"   Early stopping at epoch {ep} (best val={mejor_val:.6f})")
                break

    # Saves the loss history (for the convergence curve in the thesis).
    with open(os.path.join(CFG["DIR_SALIDA"], "historia_loss.json"), "w") as f:
        json.dump(historia, f, indent=2)
    print(f"   Model saved to: {ruta_modelo}")
    return ruta_modelo



# PHASE 2 — THRESHOLD CALIBRATION

def fase2_calibrar(ruta_modelo):
    print("\n=== PHASE 2: THRESHOLD CALIBRATION (tau = P99.5) ===")
    modelo = BiLSTMAutoencoder(
        CFG["N_FEATURES"], CFG["HIDDEN"], CFG["LATENT"],
        CFG["NUM_LAYERS"], CFG["DROPOUT"]).to(DEVICE)
    modelo.load_state_dict(torch.load(ruta_modelo, map_location=DEVICE))

    X_cal = cargar("X_calibracion.npy")
    err = error_por_ventana(modelo, X_cal)
    tau = float(np.percentile(err, CFG["PERCENTIL_TAU"]))

    print(f"   Calibration windows: {len(err)}")
    print(f"   Healthy error -> mean={err.mean():.6f}  P50={np.median(err):.6f}  "
          f"P99.5={tau:.6f}")
    print(f"   THRESHOLD tau = {tau:.6f}")

    # Saves tau and the full error distribution (for the histogram in the thesis).
    np.save(os.path.join(CFG["DIR_SALIDA"], "errores_calibracion.npy"), err)
    with open(os.path.join(CFG["DIR_SALIDA"], "umbral.json"), "w") as f:
        json.dump({"tau": tau, "percentil": CFG["PERCENTIL_TAU"]}, f, indent=2)
    return modelo, tau



# PHASES 3 and 4 — EVALUATION (specificity and infected)

def evaluar_grupo(modelo, tau, subcarpeta, etiqueta):
    """Computes rho -the fraction of anomalous windows- for every video in the group."""
    dir_grupo = os.path.join(CFG["DIR_TENSORES"], subcarpeta)
    archivos = sorted(glob.glob(os.path.join(dir_grupo, "*__X.npy")))
    resultados = []
    for ruta in archivos:
        video = os.path.basename(ruta).replace("__X.npy", "")
        X = np.load(ruta)
        if len(X) == 0:
            continue
        err = error_por_ventana(modelo, X)
        n_anom = int((err > tau).sum())
        rho = n_anom / len(err)
        dias = CFG["DIAS_PI"].get(video, None)
        resultados.append({"video": video, "n_ventanas": len(err),
                           "n_anomalas": n_anom, "rho": rho, "dias_pi": dias})
        dtxt = f"day {dias}" if dias is not None else "healthy"
        print(f"   [{etiqueta}] {video:38s} rho={rho:6.3f}  "
              f"({n_anom}/{len(err)})  {dtxt}")
    return resultados


def fase3_4_evaluar(modelo, tau):
    print("\n=== PHASE 3: SPECIFICITY TEST (unseen healthy fish) ===")
    print("   (rho should be low, ~0.005, measures false positives)")
    espec = evaluar_grupo(modelo, tau, "especificidad", "SPECIF")

    print("\n=== PHASE 4: SENSITIVITY TEST (infected) ===")
    print("   (rho is expected to grow with days post-infection)")
    sens = evaluar_grupo(modelo, tau, "test", "INFECT")

    # Saves the results (for the tables and the rho-vs-day curve in the thesis).
    with open(os.path.join(CFG["DIR_SALIDA"], "resultados_evaluacion.json"), "w") as f:
        json.dump({"especificidad": espec, "infectados": sens}, f, indent=2)

    # Specificity summary.
    if espec:
        rho_espec = np.mean([r["rho"] for r in espec])
        print(f"\n   Mean rho on unseen healthy fish: {rho_espec:.4f} "
              f"(ideally close to {1 - CFG['PERCENTIL_TAU']/100:.4f})")
    return espec, sens



# ORCHESTRATOR

def main():
    print("Bi-LSTM AUTOENCODER IPNV — starting |", DEVICE)
    ruta_modelo = fase1_entrenar()
    modelo, tau = fase2_calibrar(ruta_modelo)
    fase3_4_evaluar(modelo, tau)
    print("\nDone. Artifacts in:", CFG["DIR_SALIDA"])


if __name__ == "__main__":
    main()
